"""Build three small UI skins against the installed unmodified Civ V layouts."""
from pathlib import Path
import argparse
import hashlib
import shutil
import zipfile
from release_privacy import check_public_files

ROOT = Path(__file__).resolve().parents[1]
GUID = '{c74fe31f-6834-496f-87dc-fb1c471b7fc8}'


def build(game: Path, generate_only: bool = False, output_dir: Path | None = None):
    dlc = ROOT / 'DLC/InGameTranslateMod'
    # One stock staging room is shared by all three game versions. EUI does not
    # replace it. Add only a child context, retaining the normal lobby controls.
    lobby = (game / 'Assets/UI/FrontEnd/Multiplayer/StagingRoom.xml').read_text(encoding='utf-8-sig')
    assert lobby.count('</Context>') == 1
    lobby_bootstrap = '\t<LuaContext FileName="Assets/DLC/InGameTranslateMod/UI/InGameTranslateLobby" ID="InGameTranslateLobby" Hidden="0" />\n'
    (dlc / 'UI/StagingRoom.xml').write_text(lobby.replace('</Context>', lobby_bootstrap + '</Context>'), encoding='utf-8')
    panel = (dlc / 'UI/InGameTranslate.xml').read_text(encoding='utf-8')
    panel = panel.replace('ID="InGameTranslate"', 'ID="InGameTranslateLobby"', 1)
    (dlc / 'UI/InGameTranslateLobby.xml').write_text(panel, encoding='utf-8')
    # Package the lobby as a complete XML/Lua pair. Static LuaContext lookup
    # must use the physical asset path, and its script needs no include lookup.
    logic = (dlc / 'UI/InGameTranslate.lua').read_text(encoding='utf-8')
    helpers = '\n'.join((dlc / ('UI/' + name)).read_text(encoding='utf-8') for name in ['IGT_Text.lua','IGT_History.lua'])
    lobby_script = '-- Generated by tools/build_package.py; edit shared InGameTranslate.lua.\n'
    lobby_script += 'IGT_LOBBY = true;\nprint("IGT lobby script loaded (0.9.1 translit and native drag)");\n'
    lobby_script += helpers + '\n' + logic.replace('include("IGT_Text");', '', 1).replace('include("IGT_History");', '', 1)
    (dlc / 'UI/InGameTranslateLobby.lua').write_text(lobby_script, encoding='utf-8')
    for version, skin, name, priority, relative in [
        (0, 'BaseGame', 'BaseGame', 60, 'Assets/UI/InGame/InGame.xml'),
        (1, 'Expansion1', 'Expansion1Primary', 160, 'Assets/DLC/Expansion/UI/InGame/InGame.xml'),
        (2, 'Expansion2', 'Expansion2Primary', 260, 'Assets/DLC/Expansion2/UI/InGame/InGame.xml'),
    ]:
        source = game / relative
        if not source.exists():
            continue
        original = source.read_text(encoding='utf-8-sig')
        assert original.count('</Context>') == 1
        bootstrap = '\t<LuaContext FileName="Assets/DLC/InGameTranslateMod/UI/InGameTranslate" ID="InGameTranslateMod" Hidden="0" />\n'
        folder = dlc / f'Skin{version}'
        folder.mkdir(parents=True, exist_ok=True)
        (folder / 'InGame.xml').write_text(original.replace('</Context>', bootstrap + '</Context>'), encoding='utf-8')
        manifest = f'''<?xml version="1.0" encoding="utf-8"?>
<Civ5Package>
  <GUID>{GUID}</GUID><Version>1</Version><Priority>{priority}</Priority>
  <PTags><Tag>Version</Tag></PTags>
  <Name><Value language="en_US">Improved Chat</Value></Name>
  <Description><Value language="en_US">Client-side Improved Chat beta</Value></Description>
  <UISkin name="{name}" set="{skin}" platform="Common"><Skin>
    <Directory>UI</Directory><Directory>Skin{version}</Directory>
  </Skin></UISkin>
</Civ5Package>
'''
        (dlc / f'InGameTranslate_{version}.Civ5Pkg').write_text(manifest, encoding='utf-8')
    if generate_only:
        print('Generated native DLC layouts and lobby scripts.')
        return
    release_docs = {
        ROOT / 'docs/USER_GUIDE.txt': 'README.txt',
        ROOT / 'third-party-licenses/README.txt': 'THIRD_PARTY_NOTICES.txt',
        ROOT / 'LICENSE.txt': 'LICENSE.txt',
    }
    for required in [ROOT / 'dist/InGameTranslateCompanion.exe', *release_docs]:
        if not required.is_file():
            raise SystemExit('Missing release input: ' + str(required))
    output_dir = output_dir or ROOT / 'release'
    package = output_dir / 'Improved-Chat-beta'
    package.mkdir(parents=True, exist_ok=True)
    shutil.copytree(dlc, package / 'InGameTranslateMod', dirs_exist_ok=True)
    exe = ROOT / 'dist/InGameTranslateCompanion.exe'
    if exe.exists():
        shutil.copy2(exe, package / exe.name)
    for source, name in release_docs.items():
        shutil.copy2(source, package / name)
    for name in ['Install Improved Chat.cmd', 'install.ps1']:
        shutil.copy2(ROOT / 'release-support' / name, package / name)
    licenses = ROOT / 'third-party-licenses'
    if licenses.is_dir():
        shutil.copytree(licenses, package / licenses.name, dirs_exist_ok=True)
    # Archive an explicit list, so stale/unrelated staging files cannot leak.
    files = [package / 'InGameTranslateMod' / f.relative_to(dlc) for f in dlc.rglob('*') if f.is_file()]
    files += [package / n for n in ['InGameTranslateCompanion.exe','README.txt','THIRD_PARTY_NOTICES.txt','LICENSE.txt','Install Improved Chat.cmd','install.ps1'] if (package / n).is_file()]
    if licenses.is_dir():
        files += [package / 'third-party-licenses' / f.relative_to(licenses) for f in licenses.rglob('*') if f.is_file()]
    check_public_files(files)
    manifest = package / 'MANIFEST.sha256'
    manifest.write_text(''.join(hashlib.sha256(f.read_bytes()).hexdigest() + '  ' + f.relative_to(package).as_posix() + '\n' for f in sorted(files)),encoding='utf-8')
    files.append(manifest)
    archive = output_dir / 'Improved-Chat-beta.zip'
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
        for file in files:
            z.write(file, file.relative_to(package))
    print(archive)
    dlc_archive=output_dir / 'Improved-Chat-DLC.zip'
    with zipfile.ZipFile(dlc_archive,'w',zipfile.ZIP_DEFLATED) as z:
        for file in sorted(dlc.rglob('*')):
            if file.is_file():
                z.write(file,Path('InGameTranslateMod')/file.relative_to(dlc))
    print(dlc_archive)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--game', type=Path, default=Path("C:/Program Files (x86)/Steam/steamapps/common/Sid Meier's Civilization V"))
    parser.add_argument('--generate-only', action='store_true', help='Regenerate native DLC for development/tests without packaging a release')
    parser.add_argument('--output-dir', type=Path, help='Write verification builds outside the released artifact directory')
    args = parser.parse_args()
    build(args.game,args.generate_only,args.output_dir)
