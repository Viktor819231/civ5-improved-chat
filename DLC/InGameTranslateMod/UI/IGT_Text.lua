function IGT_Text.HasNonLatinLetters(text)
    for _, token in ipairs(tokens(tostring(text or ''))) do
        local a,b,c,d = token:byte(1,4)
        local cp = a
        if a and a >= 240 and b and c and d then cp=(a-240)*262144+(b-128)*4096+(c-128)*64+d-128
        elseif a and a >= 224 and b and c then cp=(a-224)*4096+(b-128)*64+c-128
        elseif a and a >= 192 and b then cp=(a-192)*64+b-128 end
        if cp and cp >= 128 then
            local lo,hi=1,#nonLatinLetters
            while lo<=hi do
                local mid=math.floor((lo+hi)/2); local r=nonLatinLetters[mid]
                if cp<r[1] then hi=mid-1 elseif cp>r[2] then lo=mid+1 else return true end
            end
        end
    end
    return false
end

