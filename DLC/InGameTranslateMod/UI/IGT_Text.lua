    {65,90,'latin'},{97,122,'latin'},{192,214,'latin'},{216,246,'latin'},{248,591,'latin'},{7680,7935,'latin'},
    {880,1023,'other'},{1024,1327,'cyrillic'},{1328,4351,'other'},{4352,4607,'hangul'},{12352,12543,'kana'},
    {12593,12686,'hangul'},{12784,12799,'kana'},{13312,19903,'han'},{19968,40959,'han'},{44032,55203,'hangul'},
    {63744,64255,'han'},{65382,65439,'kana'}
}
function IGT_Text.Script(text)
    local counts, best = {}, nil
    for _, token in ipairs(tokens(tostring(text or ''))) do
        if #token <= 4 then
            local a,b,c,d = token:byte(1,4)
            local cp = a
            if a and a >= 240 and b and c and d then cp=(a-240)*262144+(b-128)*4096+(c-128)*64+d-128
            elseif a and a >= 224 and b and c then cp=(a-224)*4096+(b-128)*64+c-128
            elseif a and a >= 192 and b then cp=(a-192)*64+b-128 end
            local found
            for _, r in ipairs(scriptRanges) do
                if cp and cp >= r[1] and cp <= r[2] then found = r[3]; break end
            end
            if not found and cp and cp >= 128 and IGT_Text.HasNonLatinLetters(token) then found = 'other' end
            if found then counts[found] = (counts[found] or 0) + 1 end
        end
    end
    -- Japanese mixes kanji with kana: any kana makes the message Japanese.
    if counts.kana then return 'kana' end
    for script, n in pairs(counts) do
        if not best or n > counts[best] then best = script end
    end
    return best
end

