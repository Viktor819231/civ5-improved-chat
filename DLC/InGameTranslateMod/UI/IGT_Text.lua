-- UTF-8 and Civ markup helpers. No Lua libraries beyond vanilla Lua 5.1.
IGT_Text = {}

local function tokens(text)
    local out, i = {}, 1
    while i <= #text do
        local tail = text:sub(i)
        local icon = tail:match('^(%[ICON_[A-Z0-9_]+%])') or tail:match('^(%[COLOR_[A-Z0-9_]+%])') or tail:match('^(%[ENDCOLOR%])')
        if icon then
            out[#out + 1] = icon
            i = i + #icon
        else
            local b = text:byte(i)
            local count = b < 128 and 1 or b < 224 and 2 or b < 240 and 3 or 4
            out[#out + 1] = text:sub(i, i + count - 1)
            i = i + count
        end
    end
    return out
end

function IGT_Text.SafeDisplay(text)
    local out, depth = {}, 0
    for _, token in ipairs(tokens(tostring(text or ''))) do
        if token:match('^%[COLOR_') then depth = depth + 1
        elseif token == '[ENDCOLOR]' then
            if depth > 0 then depth = depth - 1 else token = '' end
        end
        if token == '[' then token = '(' elseif token == ']' then token = ')' end
        out[#out + 1] = token
    end
    out[#out + 1] = string.rep('[ENDCOLOR]', depth)
    return table.concat(out)
end

function IGT_Text.StripColors(text)
    return (tostring(text or ''):gsub('%[COLOR_[A-Z0-9_]+%]', ''):gsub('%[ENDCOLOR%]', ''))
end

function IGT_Text.Colorize(text, color)
    if not color or color == '' then return text end
    return '[' .. color .. ']' .. IGT_Text.StripColors(text) .. '[ENDCOLOR]'
end

function IGT_Text.Split(text, maxBytes)
    maxBytes = maxBytes or 240
    text = tostring(text or ''):gsub('[\r\n]', ' ')
    if #text <= maxBytes then return {text} end
    -- Repeat the translation marker on every part, reserving numbering bytes.
    local tag = text:match('^(%(TR[^%)]*%)%s*)') or ''
    local body = text:sub(#tag + 1)
    local capacity = maxBytes - #tag - 12
    if capacity < 32 then return nil, 'Message prefix is too long.' end
    local parts, current, size, active = {}, {}, 0, {}
    for _, token in ipairs(tokens(body)) do
        local opening = token:match('^%[COLOR_') ~= nil
        local closing = token == '[ENDCOLOR]'
        local nextDepth = #active + (opening and 1 or 0) - (closing and #active > 0 and 1 or 0)
        if size + #token + nextDepth * 10 > capacity then
            parts[#parts + 1] = table.concat(current) .. string.rep('[ENDCOLOR]', #active)
            current, size = {}, 0
            for _, color in ipairs(active) do current[#current + 1] = color; size = size + #color end
        end
        if size + #token + nextDepth * 10 > capacity then return nil, 'Formatting is too long for one chat message.' end
        current[#current + 1], size = token, size + #token
        if opening then active[#active + 1] = token
        elseif closing and #active > 0 then table.remove(active) end
    end
    if #current > 0 then parts[#parts + 1] = table.concat(current) .. string.rep('[ENDCOLOR]', #active) end
    if #parts > 40 then return nil, 'Message is too long (maximum 40 parts).' end
    for i, part in ipairs(parts) do
        parts[i] = tag .. '(' .. i .. '/' .. #parts .. ') ' .. part
    end
    return parts
end

